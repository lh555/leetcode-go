package main

import "fmt"

/*
**算法描述**
1. 将数组分为两个子集，排序的和未排序的，每一轮从未排序的子集中选出最小的元素，放入排序子集
2. 重复以上步骤，直到整个数组有序
*/
func selection(a []int) {
	for i := 0; i < len(a)-1; i++ {
		// i 代表每轮选择最小元素要交换到的目标索引
		s := i // 代表最小元素的索引
		for j := s + 1; j < len(a); j++ {
			if a[s] > a[j] {
				s = j
			}
		}
		a[i], a[s] = a[s], a[i]
	}
}

func main() {
	a := []int{2, 1, 4, 7, 4, 3, 8, 9}
	selection(a)
	fmt.Println(a)
}

/*
**与冒泡排序比较**

1. 二者平均时间复杂度都是 O(n^2)
2. 选择排序一般要快于冒泡，因为其交换次数少
3. 但如果集合有序度高，冒泡优于选择
4. 冒泡属于稳定排序算法，而选择属于不稳定排序
   * 稳定排序指，按对象中不同字段进行多次排序，不会打乱同值元素的顺序
   * 不稳定排序则反之

稳定：
以数组 [2, 1, 4, 7, 4, 3, 8, 9] 为例：
初始状态：两个 4 的位置分别是索引 2 和 4
第一轮：找到最小元素 1（索引 1），与索引 0 的 2 交换 → [1, 2, 4, 7, 4, 3, 8, 9]
第二轮：从索引 1 开始，最小元素是 2，无需交换
第三轮：从索引 2 开始，找到最小元素 3（索引 5），与索引 2 的 4 交换 → [1, 2, 3, 7, 4, 4, 8, 9]
结果：原来的两个 4 的相对顺序被改变（从索引 2 和 4 变为索引 5 和 4），因此选择排序是不稳定的。
*/
